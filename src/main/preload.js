'use strict';
// Narrow, named bridge. No raw IPC, no Node, no arbitrary dispatch reaches the page.
const { contextBridge, ipcRenderer } = require('electron');
const call = (channel, ...args) => ipcRenderer.invoke(channel, ...args);
contextBridge.exposeInMainWorld('deployer', {
  prerequisites: () => call('prerequisites'),
  profiles: () => call('profiles'),
  identity: s => call('identity', s),
  login: s => call('login', s),
  install: tools => call('install', tools),
  pickSource: () => call('pick-source'),
  inspectSource: file => call('inspect-source', file),
  deploy: input => call('deploy', input),
  cancel: op => call('cancel', op),
  settings: () => call('settings'),
  setSetting: (k, v) => call('set-setting', k, v),
  resetSetting: k => call('reset-setting', k),
  history: () => call('history'),
  removeDeployments: ats => call('remove-deployments', ats),
  restore: i => call('restore', i),
  lockStatus: () => call('lock-status'),
  schoolState: () => call('school-state'),
  schoolRename: n => call('school-rename', n),
  schoolEnable: c => call('school-enable', c),
  schoolDisable: v => call('school-disable', v),
  schoolCredential: (o, c) => call('school-credential', o, c),
  externalToken: t => call('external-token', t),
  externalFetch: url => call('external-fetch', url),
  lockTotp: label => call('lock-totp', label),
  lockCreate: (id, o) => call('lock-create', id, o),
  lockVerify: (id, c) => call('lock-verify', id, c),
  lockRemove: (id, c) => call('lock-remove', id, c),
  ladderStart: (id, rung) => call('ladder-start', id, rung),
  ladderAnswer: (nonce, a) => call('ladder-answer', nonce, a),
  appdata: () => call('appdata'),
  openAppdata: () => call('open-appdata'),
  label: (i, t) => call('label', i, t),
  docs: () => call('docs'),
  changelog: () => call('changelog'),
  saveFile: (name, data) => call('save-file', name, data),
  editors: () => call('editors'),
  mediaStatus: () => call('media-status'),
  mediaPick: kind => call('media-pick', kind),
  mediaConvert: (input, preset) => call('media-convert', input, preset),
  archiveCreate: files => call('archive-create', files),
  archiveExtract: file => call('archive-extract', file),
  yamlToJson: text => call('yaml-to-json', text),
  mc: { catalog: f => call('mc-catalog', f), list: () => call('mc-list'), create: s => call('mc-create', s), start: id => call('mc-start', id), stop: id => call('mc-stop', id), command: (id, c) => call('mc-command', id, c), logs: id => call('mc-logs', id), properties: id => call('mc-properties', id), setProperties: (id, ch) => call('mc-set-properties', id, ch), backup: id => call('mc-backup', id), remove: id => call('mc-remove', id), gameRules: id => call('mc-gamerules', id), pickFolder: () => call('mc-pick-folder'), pregenerate: (id, a) => call('mc-pregenerate', id, a) },
  javaStatus: () => call('java-status'),
  ollama: { status: () => call('ollama-status'), start: () => call('ollama-start'), stop: () => call('ollama-stop'), catalog: r => call('ollama-catalog', r), tags: m => call('ollama-tags', m), pull: m => call('ollama-pull', m), remove: m => call('ollama-remove', m), chat: r => call('ollama-chat', r), chats: () => call('ollama-chats'), saveChats: d => call('ollama-save-chats', d) },
  showFile: p => call('show-file', p),
  openInEditor: (name, data, editor) => call('open-in-editor', name, data, editor),
  exportHistory: () => call('export-history'),
  dimSum: () => call('dim-sum'),
  version: () => call('version'),
  provenance: () => call('provenance'),
  updateState: () => call('update-state'),
  checkUpdates: () => call('update-check'),
  installUpdate: () => call('update-install'),
  onUpdate: fn => { const l = (_e, ev) => fn(ev); ipcRenderer.on('update', l); return () => ipcRenderer.removeListener('update', l); },
  openExternal: url => call('open-external', url),
  window: action => call('window', action),
  titleBar: o => call('title-bar', o),
  onOperation: fn => { const l = (_e, ev) => fn(ev); ipcRenderer.on('op-event', l); return () => ipcRenderer.removeListener('op-event', l); },
  onWindow: fn => { const l = (_e, ev) => fn(ev); ipcRenderer.on('window', l); return () => ipcRenderer.removeListener('window', l); },
});
